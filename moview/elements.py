def atom_symbol(atomic_number: int) -> str:
    z = int(atomic_number)
    if 0 <= z < len(ELEMENT_SYMBOLS):
        return ELEMENT_SYMBOLS[z]
    return f"Z{z}"


def covalent_radius(atomic_number: int) -> float:
    return COVALENT_RADII.get(int(atomic_number), DEFAULT_COVALENT_RADIUS)


def element_color(atomic_number: int) -> tuple[float, float, float]:
    return ELEMENT_COLORS.get(int(atomic_number), DEFAULT_ELEMENT_COLOR)
